using System;
using UnityEngine;
using WFC.Core;


namespace WFC.Terrain {
    static class TerrainRenderTraversal {
        public static void Render(TerrainRenderContext ctx, ITerrainSpriteSink sink) {
            for (int y = 0; y < ctx.height; y++) {
                for (int x = 0; x < ctx.width; x++) {
                    int t = ctx.TerrainAt(x, y);

                    switch (ctx.view) {
                        case WFCTerrainGenerator.View.SemanticPaths:
                            sink.AddFlat(ctx.semanticColorAt(y * ctx.width + x), x, y, 0);
                            continue;

                        case WFCTerrainGenerator.View.Logic:
                            sink.AddFlat(ctx.terrain.defs[t].debugColor, x, y, 0);
                            continue;

                        case WFCTerrainGenerator.View.Regions: {
                            float noise = ctx.regionNoise[y * ctx.width + x];
                            sink.AddFlat(new Color(noise, noise, noise), x, y, 0);
                            continue;
                        }

                        case WFCTerrainGenerator.View.Final:
                            break;

                        default:
                            throw new ArgumentOutOfRangeException();
                    }

                    Sprite sp = Pick(ctx.terrain.baseVariants[t], x, y, 1);
                    if (sp) sink.AddSprite(sp, x, y, 0, 0);
                    else sink.AddFlat(ctx.terrain.defs[t].debugColor, x, y, 0);
                }
            }

            if (ctx.view == WFCTerrainGenerator.View.Final && ctx.overlays) {
                RenderOverlays(ctx, sink);
            }
        }

        // The mask of overlay tile o around a cell has bit d set when the neighbour in direction d is o.
        static void RenderOverlays(TerrainRenderContext ctx, ITerrainSpriteSink sink) {
            for (int y = 0; y < ctx.height; y++) {
                for (int x = 0; x < ctx.width; x++) {
                    int t = ctx.TerrainAt(x, y);

                    for (int o = 0; o < ctx.terrain.count; o++) {
                        if (((ctx.terrain.overlayTargets[o] >> t) & 1UL) == 0) continue;
                        int mask = 0;
                        for (int d = 0; d < Dirs.Count; d++) {
                            Direction dir = (Direction)d;
                            if (ctx.TerrainAt(x + Dirs.Dx(dir), y + Dirs.Dy(dir)) != o) continue;
                            mask |= 1 << d;
                        }

                        if (mask == 0) continue;

                        int      order   = 1 + ctx.terrain.overlayRank[o];
                        Sprite[] sprites = ctx.terrain.overlayByMask[o][mask];

                        for (int layer = 0; layer < sprites.Length; layer++) {
                            sink.AddSprite(sprites[layer], x, y, order, layer + 1);
                        }
                    }
                }
            }
        }

        static Sprite Pick(Sprite[] arr, int x, int y, int salt) {
            return arr == null || arr.Length == 0 ? null : arr[(int)(HashCoord(x, y, salt) % (uint)arr.Length)];
        }

        /// <remarks>
        /// This exists, rather than using a built-in func to have deterministic pseudo-random vals w/o maintaining random state.
        /// Ensures that sprite selection remains consistent for a given tile coordinate and salt, independent of generation order.
        /// This code was generated by an LLM. Appears to be based on Dwarf Fortress' TWBT coord_hash function.
        /// </remarks>
        static uint HashCoord(int a, int b, int c) {
            unchecked {
                uint h = (uint)(a * 374761393 + b * 668265263 + c * 1013904223);
                h = (h ^ (h >> 13)) * 1274126177u;
                return h ^ (h >> 16);
            }
        }
    }
}
